import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { verifyPublic } from './verify-public.mjs';
const publicPreview = process.argv.includes('--public-preview');
const indexedTools = process.argv.includes('--indexed-tools');
const directory = path.resolve(publicPreview ? 'dist-public-preview' : 'dist');
const before = verifyPublic(directory, { publicPreview, indexedTools });
const build = spawnSync(process.execPath, ['scripts/build-public.mjs', ...(publicPreview ? ['--public-preview'] : []), ...(indexedTools ? ['--indexed-tools'] : [])], { encoding: 'utf8' });
if (build.status !== 0) throw new Error(build.stdout + build.stderr);
const after = verifyPublic(directory, { publicPreview, indexedTools });
if (before.sha256 !== after.sha256) throw new Error('Build nao reproduzivel para as mesmas entradas.');
console.log(JSON.stringify({ passed: true, consecutiveBuilds: 2, sha256: after.sha256, scope: 'Mesmo ambiente e entradas; CI remoto ainda nao executado' }, null, 2));
